#!/usr/bin/env python3
"""
Generate MPTV's in-app brand drawables for both apps, overriding :core's same-named OwnTV ones.

:core draws the in-app logo from its own vector drawables, which no string override can touch:
  owntv_wordmark_own / owntv_wordmark_tv   the two halves of the wordmark ("own" + "tv"), tinted at
                                           runtime by each app's Wordmark composable (cream + accent)
  owntv_mark_<colour> / owntv_mark_small_<colour>   the flat in-app mark (BrandMark), one per icon colour
  owntv_mark_play / owntv_mark_play_small  the play triangle BrandMark tints with the accent over a mark
  owntv_notification                       the status-bar icon core's notifications use
Resources in an app module replace a library's of the same name and qualifier, so this writes MPTV
versions of each into app/ and mobile/ (plain drawable/, the bucket core's live in — a different
density bucket would not reliably win). Same idea as core's own tools/brand/render_brand.py.

The letterforms are Poppins Bold, which both apps already ship (res/font/poppins_bold.ttf), read
straight from the TrueType outlines (stdlib only — this sandbox has no fontTools) into VectorDrawable
path data:
  wordmark   "MP" in owntv_wordmark_own, "TV" in owntv_wordmark_tv, the same 988×182 box core uses so
             the composables' sizing is untouched; white, tinted by the app like the originals
  mark       a rounded card in the launcher icon's background with "MP" over "TV" in the brand gradient
             (the simpler single "M" at 32 dp and below, where core too switches to a simpler drawing);
             all nine colours identical, as the launcher icons already are
  play       nothing — the mark has no play triangle for the accent to tint
  notification  a white "M"
"Pixel" is the one icon whose large mark both apps draw in code from core's dot grid; it is not a
drawable, so it stays core's TV set.

Usage: render_mptv_marks.py            write the drawables into both apps
       render_mptv_marks.py --check    exit 1 if what is in the repo differs from what this would write
       render_mptv_marks.py --preview DIR   also write SVG previews of each distinct drawing to DIR
"""
import argparse
import os
import struct
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT = os.path.join(ROOT, "app/src/main/res/font/poppins_bold.ttf")
RES_DIRS = ["app/src/main/res/drawable", "mobile/app/src/main/res/drawable"]
COLOURS = ["petrol", "sunflower", "cobalt", "tomato", "board", "eggshell", "olive", "olive_cream", "pixel"]

CARD_BG = "#FF0F0A1A"            # mptv_icon_bg / owntv_icon_bg: the launcher icon's background
GRADIENT = [("0", "#FF22D3EE"), ("0.55", "#FFB06BFF"), ("1", "#FFF472E0")]   # cyan → purple → pink
HEADER = "<!-- MPTV: generated by tools/brand/render_mptv_marks.py, overriding :core's drawable of the same name. Do not edit by hand. -->"


class TrueType:
    """Just enough of a TrueType reader for simple (and offset-only composite) glyph outlines."""

    def __init__(self, path):
        d = self.d = open(path, "rb").read()
        n = struct.unpack(">H", d[4:6])[0]
        self.t = {}
        for i in range(n):
            tag, _, off, ln = struct.unpack(">4sIII", d[12 + 16 * i:28 + 16 * i])
            self.t[tag.decode("latin1")] = (off, ln)
        head = self.t["head"][0]
        self.upm = struct.unpack(">H", d[head + 18:head + 20])[0]
        self.loc_fmt = struct.unpack(">h", d[head + 50:head + 52])[0]
        self.nglyphs = struct.unpack(">H", d[self.t["maxp"][0] + 4:self.t["maxp"][0] + 6])[0]
        os2 = self.t["OS/2"][0]
        self.cap_height = struct.unpack(">h", d[os2 + 88:os2 + 90])[0]
        self.nhm = struct.unpack(">H", d[self.t["hhea"][0] + 34:self.t["hhea"][0] + 36])[0]
        self.cmap = self._cmap4()
        self.loca = self._loca()

    def _cmap4(self):
        d, off = self.d, self.t["cmap"][0]
        n = struct.unpack(">H", d[off + 2:off + 4])[0]
        sub = None
        for i in range(n):
            pid, eid, so = struct.unpack(">HHI", d[off + 4 + 8 * i:off + 12 + 8 * i])
            if (pid, eid) in ((3, 1), (0, 3)) and struct.unpack(">H", d[off + so:off + so + 2])[0] == 4:
                sub = off + so
                break
        if sub is None:
            sys.exit("no format-4 cmap subtable")
        segx2 = struct.unpack(">H", d[sub + 6:sub + 8])[0]
        seg = segx2 // 2
        ends = struct.unpack(">%dH" % seg, d[sub + 14:sub + 14 + segx2])
        starts = struct.unpack(">%dH" % seg, d[sub + 16 + segx2:sub + 16 + 2 * segx2])
        deltas = struct.unpack(">%dh" % seg, d[sub + 16 + 2 * segx2:sub + 16 + 3 * segx2])
        ro = sub + 16 + 3 * segx2
        ranges = struct.unpack(">%dH" % seg, d[ro:ro + segx2])
        m = {}
        for ch in range(0x20, 0x7F):
            for i in range(seg):
                if starts[i] <= ch <= ends[i]:
                    if ranges[i] == 0:
                        g = (ch + deltas[i]) & 0xFFFF
                    else:
                        gi = ro + 2 * i + ranges[i] + 2 * (ch - starts[i])
                        g = struct.unpack(">H", d[gi:gi + 2])[0]
                        if g:
                            g = (g + deltas[i]) & 0xFFFF
                    m[chr(ch)] = g
                    break
        return m

    def _loca(self):
        off, _ = self.t["loca"]
        n = self.nglyphs + 1
        if self.loc_fmt == 0:
            return [2 * v for v in struct.unpack(">%dH" % n, self.d[off:off + 2 * n])]
        return list(struct.unpack(">%dI" % n, self.d[off:off + 4 * n]))

    def advance(self, g):
        hmtx = self.t["hmtx"][0]
        i = min(g, self.nhm - 1)
        return struct.unpack(">H", self.d[hmtx + 4 * i:hmtx + 4 * i + 2])[0]

    def bounds(self, g):
        base = self.t["glyf"][0] + self.loca[g]
        return struct.unpack(">hhhh", self.d[base + 2:base + 10])

    def glyph(self, g):
        """Contours of glyph [g]: lists of (x, y, on_curve) in font units."""
        start, end = self.loca[g], self.loca[g + 1]
        if end <= start:
            return []
        d = self.d
        base = self.t["glyf"][0] + start
        nc = struct.unpack(">h", d[base:base + 2])[0]
        if nc < 0:
            return self._composite(base)
        p = base + 10
        ends = struct.unpack(">%dH" % nc, d[p:p + 2 * nc])
        p += 2 * nc
        npts = ends[-1] + 1 if nc else 0
        il = struct.unpack(">H", d[p:p + 2])[0]
        p += 2 + il
        flags = []
        while len(flags) < npts:
            f = d[p]
            p += 1
            flags.append(f)
            if f & 8:
                flags.extend([f] * d[p])
                p += 1
        xs, x = [], 0
        for f in flags:
            if f & 2:
                x += d[p] if f & 16 else -d[p]
                p += 1
            elif not f & 16:
                x += struct.unpack(">h", d[p:p + 2])[0]
                p += 2
            xs.append(x)
        ys, y = [], 0
        for f in flags:
            if f & 4:
                y += d[p] if f & 32 else -d[p]
                p += 1
            elif not f & 32:
                y += struct.unpack(">h", d[p:p + 2])[0]
                p += 2
            ys.append(y)
        contours, s = [], 0
        for e in ends:
            contours.append([(xs[i], ys[i], bool(flags[i] & 1)) for i in range(s, e + 1)])
            s = e + 1
        return contours

    def _composite(self, base):
        d, p, out = self.d, base + 10, []
        while True:
            flags, gi = struct.unpack(">HH", d[p:p + 4])
            p += 4
            if flags & 1:
                a1, a2 = struct.unpack(">hh", d[p:p + 4])
                p += 4
            else:
                a1, a2 = struct.unpack(">bb", d[p:p + 2])
                p += 2
            if flags & (8 | 0x40 | 0x80):
                sys.exit("scaled composite glyphs are not supported")
            dx, dy = (a1, a2) if flags & 2 else (0, 0)
            for c in self.glyph(gi):
                out.append([(x + dx, y + dy, on) for x, y, on in c])
            if not flags & 0x20:
                return out


def contour_path(pts, tf):
    """One closed TrueType contour → path commands (M/L/Q/Z) through the point transform [tf]."""
    start = next((i for i, p in enumerate(pts) if p[2]), None)
    if start is None:   # no on-curve point: start at the implied midpoint of the first two
        pts = [((pts[-1][0] + pts[0][0]) / 2, (pts[-1][1] + pts[0][1]) / 2, True)] + pts
        start = 0
    seq = pts[start:] + pts[:start]
    out = ["M" + tf(seq[0][0], seq[0][1])]
    ctrl = None
    for x, y, on in seq[1:] + [seq[0]]:
        if on:
            out.append(("L" + tf(x, y)) if ctrl is None else ("Q" + tf(*ctrl) + " " + tf(x, y)))
            ctrl = None
        else:
            if ctrl is not None:    # two off-curve points in a row: an implied on-curve midpoint between them
                out.append("Q" + tf(*ctrl) + " " + tf((ctrl[0] + x) / 2, (ctrl[1] + y) / 2))
            ctrl = (x, y)
    out.append("Z")
    return "".join(out)


class Typesetter:
    def __init__(self, font):
        self.f = font

    def ink(self, text):
        """(left, right) ink extents of [text] in font units with the pen starting at 0, no kerning."""
        pen, left, right = 0, None, None
        for ch in text:
            g = self.f.cmap[ch]
            x0, _, x1, _ = self.f.bounds(g)
            left = pen + x0 if left is None else left
            right = pen + x1
            pen += self.f.advance(g)
        return left, right

    def path(self, text, scale, x, baseline):
        """pathData for [text] at [scale] (viewport units per font unit), pen at [x], [baseline] y-down."""
        pen, parts = 0, []

        def tf(px, py):
            return "%s,%s" % (fmt(x + (pen + px) * scale), fmt(baseline - py * scale))

        for ch in text:
            g = self.f.cmap[ch]
            for c in self.f.glyph(g):
                parts.append(contour_path(c, tf))
            pen += self.f.advance(g)
        return "".join(parts)

    def centred(self, text, cap_px, cx, baseline):
        """[text] with caps [cap_px] tall, ink centred on [cx]: (pathData, ink width in px)."""
        s = cap_px / self.f.cap_height
        left, right = self.ink(text)
        width = (right - left) * s
        return self.path(text, s, cx - (left + right) / 2 * s, baseline), width


def fmt(v):
    return ("%.2f" % v).rstrip("0").rstrip(".") or "0"


def vector(width_dp, height_dp, vw, vh, body, aapt=False):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n%s\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"%s\n'
        '    android:width="%sdp" android:height="%sdp"\n'
        '    android:viewportWidth="%s" android:viewportHeight="%s">\n%s</vector>\n'
        % (HEADER, ns, width_dp, height_dp, vw, vh, body)
    )


def gradient_path(path_data, x0, y0, x1, y1):
    items = "".join('            <item android:offset="%s" android:color="%s"/>\n' % (o, c) for o, c in GRADIENT)
    return (
        '    <path android:pathData="%s">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear" android:startX="%s" android:startY="%s" android:endX="%s" android:endY="%s">\n'
        "%s"
        "            </gradient>\n"
        "        </aapt:attr>\n"
        "    </path>\n" % (path_data, x0, y0, x1, y1, items)
    )


def card_path(x0, y0, x1, y1, r):
    return ("M%s,%sH%sA%s,%s 0 0 1 %s,%sV%sA%s,%s 0 0 1 %s,%sH%sA%s,%s 0 0 1 %s,%sV%sA%s,%s 0 0 1 %s,%sZ" % (
        fmt(x0 + r), fmt(y0), fmt(x1 - r), r, r, fmt(x1), fmt(y0 + r), fmt(y1 - r), r, r, fmt(x1 - r), fmt(y1),
        fmt(x0 + r), r, r, fmt(x0), fmt(y1 - r), fmt(y0 + r), r, r, fmt(x0 + r), fmt(y0)))


def render(font):
    ts = Typesetter(font)
    out = {}

    # Wordmark: core's 988 × 182 box, caps the full 182 tall, ink starting at x = 0; "MP" and "TV" share
    # one pen so the two drawables overlay into "MPTV" exactly as core's "own" + "tv" do.
    s = 182 / font.cap_height
    left, right = ts.ink("MPTV")
    if (right - left) * s > 988:
        sys.exit("wordmark too wide for core's 988 × 182 box")
    x0 = -left * s
    tv_pen = sum(font.advance(font.cmap[c]) for c in "MP") * s
    for name, text, x in (("owntv_wordmark_own", "MP", x0), ("owntv_wordmark_tv", "TV", x0 + tv_pen)):
        out[name] = vector(988, 182, 988, 182,
                           '    <path android:pathData="%s" android:fillColor="#FFFFFFFF"/>\n' % ts.path(text, s, x, 182))

    # Marks: core's 56-unit viewport (56 dp large, 32 dp small), a rounded card with the launcher
    # icon's background, letters in the brand gradient. Large: "MP" over "TV"; small: "M".
    card = '    <path android:pathData="%s" android:fillColor="%s"/>\n' % (card_path(3, 3, 53, 53, 11), CARD_BG)
    cap, gap = 15.5, 4.5
    top = 28 - (2 * cap + gap) / 2
    line1, w1 = ts.centred("MP", cap, 28, top + cap)
    line2, w2 = ts.centred("TV", cap, 28, top + cap + gap + cap)
    if max(w1, w2) > 44:
        sys.exit("monogram lines too wide for the card")
    large = card + gradient_path(line1 + line2, 6, 10, 50, 46)
    small_m, wm = ts.centred("M", 26, 28, 28 + 13)
    if wm > 44:
        sys.exit("small M too wide for the card")
    small = card + gradient_path(small_m, 6, 10, 50, 46)
    for colour in COLOURS:
        out["owntv_mark_" + colour] = vector(56, 56, 56, 56, large, aapt=True)
        out["owntv_mark_small_" + colour] = vector(32, 32, 56, 56, small, aapt=True)

    # The accent-tinted play triangle BrandMark lays over a card: the MPTV card has none, so draw nothing.
    nothing = '    <path android:pathData="M0,0h1v1h-1z" android:fillColor="#00000000"/>\n'
    out["owntv_mark_play"] = vector(56, 56, 56, 56, nothing)
    out["owntv_mark_play_small"] = vector(32, 32, 56, 56, nothing)

    # Status-bar icon: alpha only, so a plain white "M" in core's 24 dp / 56-unit frame.
    note_m, _ = ts.centred("M", 32, 28, 28 + 16)
    out["owntv_notification"] = vector(24, 24, 56, 56,
                                       '    <path android:pathData="%s" android:fillColor="#FFFFFFFF"/>\n' % note_m)
    return out


def previews(drawables, directory):
    """SVG twins of each distinct drawing, for eyeballing (solid colours: the preview renderer is basic)."""
    import re
    os.makedirs(directory, exist_ok=True)

    def paths(name, fill):
        return "".join('<path d="%s" fill="%s"/>' % (m, fill)
                       for m in re.findall(r'android:pathData="([^"]+)"', drawables[name]))

    svgs = {
        "wordmark": (988, 182, '<rect width="988" height="182" fill="#0F0A1A"/>'
                     + paths("owntv_wordmark_own", "#FFF6EE") + paths("owntv_wordmark_tv", "#86D3DB")),
        "mark_large": (56, 56, paths("owntv_mark_petrol", "#B06BFF").replace('fill="#B06BFF"', 'fill="#0F0A1A"', 1)),
        "mark_small": (56, 56, paths("owntv_mark_small_petrol", "#B06BFF").replace('fill="#B06BFF"', 'fill="#0F0A1A"', 1)),
        "notification": (56, 56, '<rect width="56" height="56" fill="#444"/>' + paths("owntv_notification", "#FFFFFF")),
    }
    for name, (w, h, body) in svgs.items():
        with open(os.path.join(directory, name + ".svg"), "w") as f:
            f.write('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d">%s</svg>\n'
                    % (w, h, w * (1 if w > 100 else 8), h * (1 if w > 100 else 8), body))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--preview", metavar="DIR")
    args = ap.parse_args()
    drawables = render(TrueType(FONT))
    if args.preview:
        previews(drawables, args.preview)
    stale = []
    for res in RES_DIRS:
        for name, xml in drawables.items():
            path = os.path.join(ROOT, res, name + ".xml")
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current == xml:
                continue
            if args.check:
                stale.append(os.path.relpath(path, ROOT))
            else:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(xml)
    if args.check:
        if stale:
            print("MPTV brand drawables are stale (re-run tools/brand/render_mptv_marks.py):\n  " + "\n  ".join(stale))
            sys.exit(1)
        print("MPTV brand drawables are up to date (%d per app)." % len(drawables))
    else:
        print("Wrote %d drawables into each of: %s" % (len(drawables), ", ".join(RES_DIRS)))


if __name__ == "__main__":
    main()
